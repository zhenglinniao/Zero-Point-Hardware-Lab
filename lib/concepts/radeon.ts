  'Documented RDNA 4 logical architecture from AMD. Block sizes and positions are illustrative; this is not a mask layout of Navi 48.';
const interpretive =
  'AMD publishes the contents of the compute engine as one diagram. Which of those blocks belong to the workgroup processor and which to each compute unit is drawn here as an interpretation of that diagram, not as a claim of exact partitioning.';

const physicalCard = (
  e: Omit<Entry, 'level' | 'representationType'> & { sources: SourceId[] },
) =>
  concept({
    physicalAccuracy: card,
    ...e,
    level: 'rx9070',
    representationType: 'physical',
  });
