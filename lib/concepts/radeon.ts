  'Illustrative geometry after the Sapphire NITRO+ RX 9070 XT. The 330.8 × 128.5 × 65.7 mm envelope, three fans, six heat pipes, magnetic backplate, rear power socket and four outputs follow published descriptions; exact shapes, fin counts and routing are approximate.';
