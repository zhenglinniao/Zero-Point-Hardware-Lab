/**
 * The AMD Radeon RX 9070 XT, as a second complete graphics card.
 *
 * The exterior and board follow the Sapphire NITRO+ RX 9070 XT, because AMD
 * did not sell a card of its own for this GPU. The chip scales follow AMD's own
 * description of RDNA 4 at Hot Chips 2025 and the RX 9070 XT specification
 * page: four shader engines, eight workgroup processors in each, two compute
 * units in each workgroup processor, 64 compute units in all.
 *
 * Every id carries an `rx` prefix so that nothing here can collide with the
 * RTX 5090 catalogue, which uses bare names such as `fan` and `pcb`.
 */

